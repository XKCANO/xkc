	//   |||+-----------------> NC
	//   ||+------------------> NC
	//   |+-------------------> NC
	//   +--------------------> NC

	//输入使能
	GPIOB->OEC |= (1 << 3) + (1 << 4) + (1 << 5);
	//输出使能
	GPIOB->OES |= (1 << 0) + (1 << 1) + (1 << 2) + 
	              (1 << 6) + (1 << 7) +
							  (1 << 8) + (1 << 9) + (1 << 10) + (1 << 11) + 
							  (1 << 12) + (1 << 13) + (1 << 14) + (1 << 15);
	//输出复位
	GPIOB->BRR |= 0xFDC7;
	//输出置位
	GPIOB->BSR |= 0x0200;
	//开漏失能
	GPIOB->ODC |= 0xFFFF;
	//开漏使能
	GPIOB->ODS |= 0x0200;
	//上拉失能
	GPIOB->PUC |= 0xFFFF;
	
	//下拉失能
	GPIOB->PDC |= 0xFFFF;
  //下拉使能
  GPIOB->PDS |= 0x0008;  //IO_PIN
	
	//施密特触发使能
