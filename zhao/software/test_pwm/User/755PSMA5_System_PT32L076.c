	//   |||| |||| ||+--------> NC
	//   |||| |||| |+---------> NC
	//   |||| |||| +----------> NC
	//
	//   |||| |||+------------> NC
	//   |||| ||+-------------> NC
	//   |||| |+--------------> NC
	//   |||| +---------------> NC
	//
	//   |||+-----------------> NC
	//   ||+------------------> I12(开漏输出)
	//   |+-------------------> I13(开漏输出)
	//   +--------------------> BOOT(输出)
	
	//输入使能
	GPIOC->OEC |= 0;
	//输出使能
	GPIOC->OES |= 0xFFFF;
	//输出复位
	GPIOC->BRR |= 0x9FFF;
	//输出置位
	GPIOC->BSR |= 0x6000;
	//开漏失能
	GPIOC->ODC |= 0xFFFF;
	//开漏使能
	GPIOC->ODS |= 0x6000;
	//上拉失能
