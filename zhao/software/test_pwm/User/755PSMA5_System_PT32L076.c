	//   |||| |||| |||| ||+---> I21(开漏输出)
	//   |||| |||| |||| |+----> NC
	//   |||| |||| |||| +-----> NC
	//
	//   |||| |||| |||+-------> NC
	//   |||| |||| ||+--------> NC
