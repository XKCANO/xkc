	//模拟失能
	AFIOA->ANAC |= 0xFFFF;

  //PB 0000 0010 0000 0000
	//   |||| |||| |||| |||+--> BL_EN(输出)
	//   |||| |||| |||| ||+---> BTS(输出)
	//   |||| |||| |||| |+----> PB2(STM32)
	//   |||| |||| |||| +-----> IO_PIN(输入)
