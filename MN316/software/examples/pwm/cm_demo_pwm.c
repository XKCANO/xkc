/**
 * @brief  pwm接口函数测试示例
 *
 * @return  void
 *
 * @details More details
 */
void cm_test_pwm(unsigned char **cmd, int len)
{
    int freq = 30000;//30KHZ
    int duty = 500;//占空比500‰
    
	CM_DEMO_PWM_LOG("pwm test start!!\n");
	
    cm_pwm_open(CM_PWM_DEV_0, freq, duty);//频率及占空比设置
    osDelay(2000);
    cm_pwm_close(CM_PWM_DEV_0);
	
	CM_DEMO_PWM_LOG("pwm test end!!\n");
	
}
