int32_t cm_misc_str_parse(const char *resp_line, const char *resp_expr, ...)
{
    va_list args;
    int resp_args_num = 0;

    va_start(args, resp_expr);

    resp_args_num = vsscanf(resp_line, resp_expr, args);

    va_end(args);

    return resp_args_num;
}



