/*** 4096 / 3.0V = 1365 ***/
#define  BANDGAP_1P0V  1365
/* -------------------------------------------------------------------------- */
/*
 * @brief 修改AD值
 *
 * @param [in] data: 当前值
 * @param [in] vref: 当前参考电压值
 *
 * @return: 修正后的AD值
 *
 * @details
 */
uint32_t fe_correcting_ad_data(uint32_t data, uint32_t vref)
{
	uint32_t i;
	
	i = data * BANDGAP_1P0V / vref;
	return i;
}


/*
 * @brief 获取平均值
 *
 * @param [in] p：数据缓存首地址
 * @param [in] l：数据长度
 *
 * @return: 平均值
 *
 * @details
 */
uint32_t fe_get_average(uint16_t *p, uint32_t l)
{
	uint32_t i,s;
	
	i = s = 0;
	do{
		s += p[i];
		i++;
	}while(i < l);
	
	return (s / l);
}

/*
 * @brief 获取最大值
 *
 * @param [in] p：数据缓存首地址
 * @param [in] l：数据长度
 *
 * @return: 最大值
 *
 * @details
 */
uint32_t fe_get_maximum(uint16_t *p, uint32_t l)
{
	uint32_t i, max;
	
	max = i = 0;
	do{
		if(p[i] > max)
		{
			max = p[i];
		}
		i++;
	}while(i < l);
	
	return max;
}

/*
 * @brief 获取最小值
 *
 * @param [in] p：数据缓存首地址
 * @param [in] l：数据长度
 *
 * @return: 最小值
 *
 * @details
 */
uint32_t fe_get_minimum(uint16_t *p, uint32_t l)
{
	uint32_t i,min;
	
	i = 0;
	min = 0xFFFF;
	do{
		if(p[i] < min)
		{
			min = p[i];
		}
		i++;
	}while(i < l);
	
	return min;
}

/*
 * @brief 一维浮点数组左移
 *
 * @param [in] p 数据缓存首地址
 * @param [in] n 数据长度
 *
 * @return: 无
 * 
 * @details
 */
void fe_float_data_move_to_left(float *p, uint32_t l)
{
	uint32_t i = 0;
	do{
		p[i] = p[i + 1];
		i++;
	}while(i < (l - 1));
}

