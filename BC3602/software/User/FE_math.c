/*
 * @brief 数据白化
 *
 * @param [in] p 数据缓存首地址
 * @param [in] l 数据长度
 *
 *
 * @return: 无
 * 
 * @details
 * g(x) = X7+X4+1
 * 白化种子0b0101010
 */
void fe_data_whitening_pn7(unsigned char *p, uint32_t l)
{
	uint32_t i;
	i = 0;
	do{
		p[i] = p[i] ^ WHITENING_TABLE[i];
		i++;
	}while(i < l);
}


