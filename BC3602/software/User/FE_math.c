/*
 * @brief 数据反转
 *
 * @param [in] d 数据
 * @param [in] l 数据位
 *
 *
 * @return: 反转的数据
 * 
 * @details
 *
 */
uint32_t fe_invert_data(uint32_t d, uint32_t l)
{
	uint32_t k;
	k = 0;
	while(l--)
	{
		k <<= 1;
		if((d & 0x1) == 0)
			k &= 0xFFFFFFFE;
		else
			k |= 0x1;
		d >>= 1;
	}
	return k;
}

/*
 * @brief CRC校验
 *
 * @param [in] p 数据缓存首地址
 * @param [in] l 数据长度
 *
 *
 * @return: 校验值
 * 
 * @details
 * g(x) = X16+X12+X5+1(0x11021)
 * 初始值0x0000
 */
uint32_t fe_calculate_crc(unsigned char *p, unsigned char l)
{
	uint32_t i,d,c = 0;
	while(l--)
	{
		d = *(p++);
		i = (d >> 4) & 0x0000000F;
		i = ((c >> 12) & 0x0000000F) ^ i;
		c = (c << 4) ^ CRC_CCITT_TABLE[i];
		
		i = ((c >> 12) & 0x0000000F) ^ (d & 0x0000000F);
		c = (c << 4) ^ CRC_CCITT_TABLE[i];
	};
	return (c & 0x0000FFFF);
}


